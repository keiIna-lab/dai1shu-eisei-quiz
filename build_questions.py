def distractors(facts, index, rot, column):
    n = len(facts)
    picked = []
    start = 1 + rot * 4
    for k in range(4):
        picked.append(facts[(index + start + k) % n][column])
    if len(set(picked)) != 4:
        raise SystemExit("誤答が重複する")
    return picked


def add_item(items, cat, topic_name, stem, correct, wrongs, explain, kind):
    if correct in wrongs or len(set(wrongs)) != 4:
        raise SystemExit("選択肢が壊れている: " + stem[:30])
    key = "\n".join([stem, correct, *sorted(wrongs)])
    seed = int(hashlib.sha256(key.encode("utf-8")).hexdigest()[:8], 16)
    choices = [correct, *wrongs]
    random.Random(seed).shuffle(choices)
    items.append({
        "id": "q" + hashlib.sha1(key.encode("utf-8")).hexdigest()[:10],
        "category": cat,
        "topic": topic_name,
        "text": stem,
        "choices": choices,
        "answer": choices.index(correct),
        "explain": explain,
        "kind": kind,
    })


def expand():
    stems_true = [
        "{0}に関する次の記述のうち、正しいものはどれか。",
        "{0}について、適切なものはどれか。",
        "{0}の説明として、正しいものはどれか。",
        "{0}に関する記述として、適切なものはどれか。",
    ]
    stems_false = [
        "{0}に関する次の記述のうち、誤っているものはどれか。",
        "{0}について、適切でないものはどれか。",
        "{0}の説明として、誤っているものはどれか。",
        "{0}に関する記述として、誤っているものはどれか。",
    ]
    items = []
    for cat, name, facts in TOPICS:
        for i, (true, false, explain) in enumerate(facts):
            for rot in (0, 1):
                add_item(
                    items, cat, name,
                    stems_true[(i + rot) % 4].format(name),
                    true, distractors(facts, i, rot, 1),
                    explain + "正解以外は、条件や数値を取り違えた記述である。",
                    "true",
                )
                add_item(
                    items, cat, name,
                    stems_false[(i + rot) % 4].format(name),
                    false, distractors(facts, i, rot, 0),
                    explain,
                    "false",
                )
    return items


def audit(items):
    problems = []
    if len(items) != 1000:
        problems.append("問題数が1000ではない: %d" % len(items))
    ids = set()
    keys = set()
    answers = Counter()
    for q in items:
        if q["id"] in ids:
            problems.append("id重複")
        ids.add(q["id"])
        key = q["text"] + "|" + "|".join(q["choices"])
        if key in keys:
            problems.append("同一問題: " + q["id"])
        keys.add(key)
        if len(q["choices"]) != 5 or len(set(q["choices"])) != 5:
            problems.append("選択肢: " + q["id"])
        if q["answer"] not in range(5):
            problems.append("答え: " + q["id"])
        answers[q["answer"]] += 1
        correct = q["choices"][q["answer"]]
        if q["kind"] == "true" and correct not in TRUES:
            problems.append("正解が真の文でない: " + q["id"])
        if q["kind"] == "false" and correct not in FALSES:
            problems.append("正解が誤の文でない: " + q["id"])
        if q["kind"] == "true":
            for choice in q["choices"]:
                if choice != correct and choice not in FALSES:
                    problems.append("誤答が偽の文でない: " + q["id"])
        if q["kind"] == "false":
            for choice in q["choices"]:
                if choice != correct and choice not in TRUES:
                    problems.append("正答以外が真の文でない: " + q["id"])
        if len(q["explain"]) < 20:
            problems.append("解説が短い: " + q["id"])
    for n, count in answers.items():
        if count < 150:
            problems.append("正解位置 %d が偏っている: %d" % (n, count))
    return problems


